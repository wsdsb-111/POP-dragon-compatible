'use strict';
// Interpret shipping PDX; opinion storage is a finite primitive, not the CK3 engine.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const helper = path.join(__dirname, 'wyvern-v1311-finite-helper.js');
let text = fs.readFileSync(helper, 'utf8');
const marker = 'if (key === "add_hook")';
assert.ok(text.includes(marker));
text = text.replace(marker, `if (key === "add_opinion" || key === "remove_opinion") {
        const target = atom(scalar(operand, "target", key), current, env, parameters);
        const modifier = scalar(operand, "modifier", key);
        env.opinions ||= new Map();
        const id = current.id + ":" + target.id + ":" + modifier;
        if (key === "remove_opinion") env.opinions.delete(id);
        else env.opinions.set(id, { actor: current, target, modifier, months: Number(scalar(operand, "months", key)) });
        return;
      }
      ` + marker);
const compiled = new Module(helper, module);
compiled.filename = helper; compiled.paths = module.paths; compiled._compile(text, helper);
const h = compiled.exports.createHarness(['wyvern-bloodline', 'wyvern-kings', 'dragon-creed']);
const white = h.character('white', { faith: 'faith:mm_dragon_creed' });
white.rite = { id: 'mm_dragon_white' };
const black = h.character('black', { faith: 'faith:mm_dragon_creed' });
black.rite = { id: 'mm_dragon_black' };
const fire = h.character('fire', { faith: 'faith:mm_dragon_creed' });
fire.rite = { id: 'mm_dragon_fire' };
const env = h.environment();
env.globalLists.set('mm_dragon_creed_members', [white, black, fire]);
for (let i = 0; i < 2; i++) h.run('mm_v1312_update_white_opinions_effect', white, env);
assert.equal(env.opinions.size, 1, 'refresh never stacks');
const [opinion] = env.opinions.values();
assert.equal(opinion.actor, white); assert.equal(opinion.target, black); assert.equal(opinion.months, 2);
black.rite = { id: 'mm_dragon_earth' };
h.run('mm_v1312_update_white_opinions_effect', white, env);
assert.equal(env.opinions.size, 0, 'former black target is removed');
black.rite = { id: 'mm_dragon_black' };
h.run('mm_v1312_update_white_opinions_effect', white, env);
white.faith = 'faith:other';
h.run('mm_v1312_update_white_opinions_effect', white, env);
assert.equal(env.opinions.size, 0, 'departing observer is cleared');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, 'patches/dragon-creed/mod', name), 'utf8');
assert.match(read('common/opinion_modifiers/mm_v1312_rite_opinions.txt'), /opinion = -30/);
assert.match(read('common/religion/tenet_types/mm_dragon_creed.txt'), /mm_tenet_sea_second = \{\s*icon = \w+\s*character_modifier = \{ general_opinion = 20 \}/);
const sogn = read('common/modifiers/mm_v1311_mechanics.txt').match(/mm_v1311_sky_sogn = \{([^}]*)\}/)[1];
assert.doesNotMatch(sogn, /supply_loss_winter/, 'the engine rejects this province-only modifier in character scope');
assert.match(sogn, /movement_speed = 0.15/);
assert.match(sogn, /prowess = 5/);
console.log('v1.3.12 rite opinion and corrected Sogn modifier fixtures passed; winter supply deferred');
