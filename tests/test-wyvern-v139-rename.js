'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createHarness } = require('./wyvern-v134-finite-helper');
const root = path.resolve(__dirname, '..');
const upstream = process.env.CK3_WYVERN_MOD_DIR || 'D:/SteamLibrary/steamapps/workshop/content/1158310/3811316052';
const gui = fs.readFileSync(path.join(root, 'patches/dragon-culture/mod/gui/event_window_widgets/myv_wyvern_name_input.gui'), 'utf8');
assert.match(gui, /datacontext\s*=\s*"\[EventWindowWidgetNameCharacter\.GetCharacter\]"/);
assert.match(gui, /text\s*=\s*"\[EventWindowWidgetNameCharacter\.GetCurrentName\]"/);
assert.match(gui, /ontextedited\s*=\s*"\[EventWindowWidgetNameCharacter\.OnEditCurrentName\]"/);
assert.match(gui, /datacontext\s*=\s*"\[Character\.GetCulture\]"/);
assert.match(gui, /EventWindowWidgetNameCharacter\.SetCurrentName\( EventWindowWidgetNameCharacter\.GetRandomAvailableCultureName \)/);
assert.doesNotMatch(gui, /GetPlayer|GetScriptedGui|set_culture|change_first_name/);
assert.match(fs.readFileSync(path.join(root, 'patches/dragon-culture/mod/localization/simp_chinese/mm_dragon_culture_l_simp_chinese.yml'), 'utf8'), /mm_dragon_rename_local_culture_name:0 "取当地文化姓名"/);
const eventFile = path.join(upstream, 'events/myv_wyvern_rename_events.txt');
if (fs.existsSync(eventFile)) {
  const h = createHarness([]);
  const ast = h.parsePdx(fs.readFileSync(eventFile, 'utf8'), eventFile);
  const event = ast.find(n => n.key === 'myv_wyvern_rename.0001').value;
  const widget = event.find(n => n.key === 'widgets').value.find(n => n.key === 'widget').value;
  assert.equal(widget.find(n => n.key === 'gui').value, 'myv_wyvern_name_input');
  assert.equal(widget.find(n => n.key === 'controller').value, 'name_character');
  assert.equal(widget.find(n => n.key === 'setup_scope').value[0].key, 'scope:myv_named_wyvern');
  const options = event.filter(n => n.key === 'option').map(n => n.value);
  const cancel = options.find(n => n.some(v => v.key === 'name' && v.value === 'myv_wyvern_rename.0001.cancel'));
  assert.deepEqual(Array.from(cancel, n => n.key), ['name', 'is_cancel_option']);
  assert.equal(cancel.find(n => n.key === 'is_cancel_option').value, 'yes');
  const confirm = options.find(n => n.some(v => v.key === 'name' && v.value === 'myv_wyvern_rename.0001.confirm'));
  assert.ok(confirm); assert.equal(confirm.some(n => n.key === 'is_cancel_option'), false);
} else console.log('SKIP upstream rename-event check: source unavailable');
console.log('v139 existing dragon rename control structure passed');
